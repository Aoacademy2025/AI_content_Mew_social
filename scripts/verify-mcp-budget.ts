// Execute the actual receipt guard, with the worker's actual source mapping.
// Provider work is deliberately downstream of this guard and never invoked.
async function receiptReproduction() {
  const { mcpBrollJobFields } = await import("../src/lib/mcp/broll-source");
  const { parseAutoMixReceiptImageCeiling } = await import("../src/lib/automix-plan");
  const route = readFileSync("src/app/api/videos/fetch-stock/route.ts", "utf8");
  const start = route.indexOf("    if (download && !isAdmin && maxAiImages === null");
  const end = route.indexOf("    /** Reduce only unpaid/new AI slots.", start);
  assert.ok(start > 0 && end > start);
  const code = ts.transpileModule(route.slice(start, end), { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
  const guard = new Function("download", "isAdmin", "maxAiImages", "aiSlotsNeedingGeneration", "NextResponse", code);
  const fields = mcpBrollJobFields("automix") as Record<string, unknown>;
  const cap = parseAutoMixReceiptImageCeiling(fields.maxAiImages);
  const reply = (admin: boolean) => guard(true, admin, cap, () => [1, 3], { json: (body: unknown, options: unknown) => ({ body, options }) });
  assert.equal(reply(false).body.error, "render_receipt_required");
  assert.equal(reply(true), undefined);
  console.log("REPRO ordinary USER AutoMix missing cap => render_receipt_required; ADMIN bypass masks failure");
}

